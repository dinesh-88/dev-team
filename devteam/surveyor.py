"""Surveyor agent: looks through a folder of repositories and writes repos.toml.

Run on its own with:  devteam agent surveyor   (or python -m devteam.surveyor)

Incoming message:  text part = instructions, plus any hints ("tests run in docker")
                   data part = {"folder": "/path/to/your/code", "only": ["name", ...]?}
Result artifacts:  "repos" data part = {"repos": [{"name", "path", "description",
                                                   "base", "setup", "test"}]}
                   "repos.toml" file part = the same, ready to save

Finding the repositories is plain Python (any folder with a .git entry). The
model only reads them and fills in what a human would: a short name, a
description, and how to install and test each one.

Note: the `setup` and `test` commands here are SUGGESTED by a model. QA runs
them later, so the client saves the file for you to review; it never runs them.
"""

import json
import re
import subprocess
import tomllib
from pathlib import Path

from a2a.helpers import get_data_parts, new_data_part
from a2a.types import AgentSkill, Part

from devteam import brain, mock
from devteam.a2a_server import TeamAgent, build_card, main
from devteam.tools import Toolbox

PORT = 9104  # when run on its own; `devteam run` picks free ports
MAX_DEPTH = 3  # how deep below the folder to look for repositories
MAX_REPOS = 40
SKIP_DIRS = {"node_modules", "vendor", "venv", ".venv", "dist", "build", "target", "__pycache__"}

SYSTEM = """You are setting up a small software team that will later change these
repositories. Read each repository with your tools: its README, its build and
dependency files (package.json, composer.json, pyproject.toml, requirements*.txt,
go.mod, pom.xml, build.gradle, Gemfile, Makefile, Dockerfile, docker-compose.yml)
and its CI config (.github/workflows, .gitlab-ci.yml, bitbucket-pipelines.yml).
Do not guess what you can read.

Then call submit_repos with one entry per repository:
- name: short, lowercase, unique, letters/digits/dashes, e.g. "core-backend", "web".
- description: two or three sentences for a planner deciding which repos a
  change touches: language and framework, what it owns (data, APIs, UI), and
  how it talks to the other repositories listed here if you can tell.
- setup: the command that installs dependencies in a FRESH checkout of the repo
  (e.g. "npm ci", "composer install", "pip install -e ."). Empty if none needed.
- test: the command that runs the unit tests without a network, a database
  server or user input (e.g. "npm test -- --watchAll=false", "vendor/bin/phpunit",
  "pytest -q"). Empty if the repo has no tests or they need services you
  cannot assume are running.
- notes: anything a human should check before trusting setup/test. Empty if none.

Commands run from the repository root in a plain shell. Prefer what the CI
config runs. Never suggest commands that deploy, push, publish, delete data
or need secrets."""


def find_repos(folder: Path) -> list[Path]:
    """Every git repository at or below `folder` (not inside another repo)."""
    if (folder / ".git").exists():
        return [folder]
    found = []

    def walk(directory: Path, depth: int) -> None:
        try:
            children = sorted(p for p in directory.iterdir() if p.is_dir() and not p.is_symlink())
        except OSError:
            return
        for child in children:
            if child.name.startswith(".") or child.name in SKIP_DIRS:
                continue
            if (child / ".git").exists():  # a folder, or a file for worktrees/submodules
                found.append(child)
            elif depth < MAX_DEPTH:
                walk(child, depth + 1)

    walk(folder, 1)
    return found


def default_branch(repo: Path) -> str:
    """The remote's default branch if a local branch of that name exists, else ''."""
    def git(*args: str) -> str:
        result = subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True)
        return result.stdout.strip() if result.returncode == 0 else ""

    remote_head = git("symbolic-ref", "--short", "refs/remotes/origin/HEAD")  # "origin/main"
    for branch in (remote_head.removeprefix("origin/"), "main", "master"):
        if branch and git("rev-parse", "--verify", "--quiet", f"refs/heads/{branch}"):
            return branch
    return ""


def unique_name(wanted: str, fallback: str, taken: set[str]) -> str:
    name = "-".join(re.findall(r"[a-z0-9]+", (wanted or fallback).lower())) or "repo"
    candidate, number = name, 2
    while candidate in taken:
        candidate, number = f"{name}-{number}", number + 1
    taken.add(candidate)
    return candidate


def to_toml(folder: Path, repos: list[dict]) -> str:
    """Render repos.toml. JSON strings are valid TOML basic strings."""
    lines = [
        f"# Generated by the Surveyor agent from {folder}",
        "# REVIEW BEFORE USE: the setup and test commands were suggested by a model,",
        "# and QA runs them on your machine. Edit the descriptions freely.",
    ]
    for repo in repos:
        lines += ["", "[[repo]]"]
        for key in ("name", "path", "description", "base", "setup", "test"):
            if repo.get(key):
                lines.append(f"{key} = {json.dumps(repo[key], ensure_ascii=False)}")
        if repo.get("notes"):
            lines += [f"# check: {line}" for line in repo["notes"].splitlines() if line.strip()]
    text = "\n".join(lines) + "\n"
    tomllib.loads(text)  # fail here rather than in the orchestrator
    return text


def finish_tool(keys: list[str]) -> dict:
    return {
        "name": "submit_repos",
        "description": "Hand in one entry per repository.",
        "input_schema": {
            "type": "object",
            "properties": {
                "repos": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "properties": {
                            "repo": {"type": "string", "enum": keys,
                                     "description": "The repository, as named in your tools"},
                            "name": {"type": "string"},
                            "description": {"type": "string"},
                            "setup": {"type": "string"},
                            "test": {"type": "string"},
                            "notes": {"type": "string"},
                        },
                        "required": ["repo", "name", "description", "setup", "test"],
                    },
                }
            },
            "required": ["repos"],
        },
    }


class Surveyor(TeamAgent):
    async def work(self, context, updater):
        info = get_data_parts(context.message.parts)[0]
        folder = Path(info["folder"]).expanduser().resolve()
        if not folder.is_dir():
            raise ValueError(f"{folder} is not a folder")

        paths = find_repos(folder)
        if info.get("only"):
            paths = [p for p in paths if p.name in info["only"]]
        if not paths:
            raise ValueError(f"No git repositories found in {folder} (searched {MAX_DEPTH} levels)")
        if len(paths) > MAX_REPOS:
            raise ValueError(f"Found {len(paths)} repositories in {folder}; the limit is "
                             f"{MAX_REPOS}. Pick some with `only`, or point at a smaller folder.")

        # Tool names are the folder names (made unique), read-only.
        roots = {}
        for path in paths:
            roots[unique_name(path.name, "repo", set(roots))] = path
        await self.progress(context, updater, f"Found {len(roots)} repo(s): {', '.join(roots)}")

        toolbox = Toolbox({key: str(path) for key, path in roots.items()})
        chat = brain.Conversation(SYSTEM, toolbox, finish_tool(sorted(roots)))
        listing = "\n".join(f"- {key}: {path}" for key, path in roots.items())
        answer = await chat.ask(
            f"{context.get_user_input()}\n\nRepositories:\n{listing}",
            **self.reporters(context, updater), mock=mock.SURVEYOR,
        )

        proposed = {entry["repo"]: entry for entry in answer["repos"] if entry["repo"] in roots}
        taken: set[str] = set()
        repos = []
        for key, path in roots.items():  # every repo found, even if the model skipped it
            entry = proposed.get(key, {"notes": "The model did not describe this repo."})
            repos.append({
                "name": unique_name(entry.get("name", ""), key, taken),
                "path": str(path),
                "description": entry.get("description", "").strip(),
                "base": default_branch(path),
                "setup": entry.get("setup", "").strip(),
                "test": entry.get("test", "").strip(),
                "notes": entry.get("notes", "").strip(),
            })

        await updater.add_artifact([new_data_part({"repos": repos})], name="repos")
        await updater.add_artifact(
            [Part(text=to_toml(folder, repos), filename="repos.toml", media_type="application/toml")],
            name="repos.toml",
        )


CARD = build_card(
    name="Surveyor",
    description="Finds the git repositories in a folder and describes them for the team.",
    skill=AgentSkill(
        id="survey",
        name="Generate repos.toml",
        description="Send instructions and hints as text and {folder, only?} as data. Returns a `repos` "
        "data artifact and a `repos.toml` file artifact. Setup/test commands are suggestions.",
        tags=["setup", "multi-repo"],
    ),
)

if __name__ == "__main__":
    main(CARD, Surveyor(), PORT)
